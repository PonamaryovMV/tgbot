export function hydrateDataIcons(root = typeof document !== "undefined" ? document : null) {
  if (!root || typeof root.querySelectorAll !== "function") return;
  root.querySelectorAll("[data-icon]").forEach((el) => {
    const name = el.getAttribute("data-icon");
    if (!name) return;
    const iconClass = el.getAttribute("data-icon-class") || "";
    el.innerHTML = renderIcon(name, iconClass);
  });
  root.querySelectorAll("[data-icon-badge]").forEach((el) => {
    const name = el.getAttribute("data-icon-badge");
    if (!name) return;
    const color = el.getAttribute("data-icon-color") || undefined;
    const bg = el.getAttribute("data-icon-bg") || undefined;
    const className = el.getAttribute("data-icon-badge-class") || "";
    const iconClass = el.getAttribute("data-icon-class") || "";
    el.innerHTML = renderIconBadge(name, { color, bg, className, iconClass });
  });
}
