const DEFAULT_THEME = T.blue;

function normalizeIconToken(raw) {
  return String(raw || "")
    .replace(/\uFE0F/g, "")
    .trim();
}

export function renderIcon(name, className = "") {
  const cls = className ? `app-icon ${className}`.trim() : "app-icon";
  const body = SVG_ICON_PATHS[name] || SVG_ICON_PATHS.package;
  return `<svg class="${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.9" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;
}

export function renderIconBadge(name, options = {}) {
  const {
    color,
    bg,
    className = "",
    iconClass = ""
  } = options || {};
  const theme = ICON_THEMES[name] || DEFAULT_THEME;
  const c = color || theme.color;
  const background = bg || theme.bg;
  const cls = className ? `ico-badge ${className}`.trim() : "ico-badge";
  return `<span class="${cls}" style="--ico-color:${c};--ico-bg:${background};" aria-hidden="true">${renderIcon(name, iconClass)}</span>`;
}

